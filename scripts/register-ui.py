"""Register generated UI silhouettes without changing the original raster assets."""
from pathlib import Path
import json
from PIL import Image

root = Path(__file__).resolve().parent.parent
records = {}
sources = [
    ('ui/v2/frames-v2.png', [
        ('ui-frame', (0, 110, 560, 530)),
        ('ui-menu', (570, 0, 1030, 540)),
        ('ui-paper', (1040, 0, 1536, 540)),
        ('ui-header', (0, 560, 550, 1024)),
        ('ui-toast', (550, 560, 1030, 1024)),
        ('ui-book', (1030, 550, 1536, 1024)),
    ]),
    ('ui/v2/details-v2.png', [
        (name, (round(i % 4 * 1774 / 4), round(i // 4 * 887 / 2),
                round((i % 4 + 1) * 1774 / 4), round((i // 4 + 1) * 887 / 2)))
        for i, name in enumerate(['ui-button', 'ui-hover', 'ui-selected', 'ui-close',
                                   'ui-osmanthus', 'ui-corner', 'ui-divider', 'ui-bookmark'])
    ]),
]
for file, regions in sources:
    image = Image.open(root / 'public/assets' / file).convert('RGBA')
    for name, (left, top, right, bottom) in regions:
        bounds = image.getchannel('A').crop((left, top, right, bottom)).point(lambda a: 255 if a > 225 else 0).getbbox()
        if not bounds:
            raise ValueError(f'Empty UI asset: {name}')
        x0, y0, x1, y1 = bounds
        padding = 2
        x0, y0 = max(0, x0-padding), max(0, y0-padding)
        x1, y1 = min(right-left, x1+padding), min(bottom-top, y1+padding)
        records[name] = {'file': file, 'region': {
            'x': left+x0, 'y': top+y0, 'width': x1-x0, 'height': y1-y0,
            'canvasWidth': image.width, 'canvasHeight': image.height,
        }}
(root / 'src/content/ui-regions.ts').write_text(
    '// Generated by scripts/register-ui.py. Originals are preserved.\n'
    'export const uiRegions = ' + json.dumps(records, ensure_ascii=False, indent=2) + ' as const;\n', encoding='utf-8')
print(f'Registered {len(records)} UI surfaces and ornaments.')
