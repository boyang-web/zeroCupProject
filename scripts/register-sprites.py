"""Read sprite alpha bounds and write region metadata. Never changes raster files."""
from pathlib import Path
from PIL import Image
import json

root = Path(__file__).resolve().parent.parent
names = ['prop-steamer', 'prop-open-steamer', 'prop-buns', 'prop-board',
         'prop-apron', 'prop-ledger', 'prop-rota', 'prop-envelope',
         'prop-bag', 'prop-brace', 'prop-tea', 'prop-photo',
         'prop-calendar', 'prop-book', 'prop-keys', 'prop-stool']
records = {}
datasets = [('morning/props-v1.png', 4, 4, names), ('morning/people-v1.png', 2, 1, ['chen', 'ning']),
            ('ui/wood-v1.png', 3, 4, ['ui-frame','ui-book','ui-menu','ui-button','ui-hover','ui-selected','ui-header','ui-tab','ui-close','ui-toggle','ui-toast','ui-slider']),
            ('noon/props-v1.png', 4, 2, ['noodle-bowl','seasoning','printer','phone-stand','food-menu','blue-ledger','chopsticks','order-slip']),
            ('noon/people-v1.png', 3, 1, ['qin','chuan','tian'])]
for file, cols, rows, ids in datasets:
    image = Image.open(root / 'public/assets' / file).convert('RGBA')
    width, height = image.size
    for index, name in enumerate(ids):
        left, top = round(index % cols * width / cols), round(index // cols * height / rows)
        right, bottom = round((index % cols + 1) * width / cols), round((index // cols + 1) * height / rows)
        if file == 'ui/wood-v1.png' and name in ('ui-hover', 'ui-selected'):
            # The previous row's tassels cross the grid boundary above these buttons.
            # Use the normal button's top so transparent space is not registered as wood.
            top = records['ui-button']['region']['y']
        bounds = image.getchannel('A').crop((left, top, right, bottom)).point(lambda v: 255 if v > 160 else 0).getbbox()
        if not bounds:
            raise ValueError(f'Empty sprite: {name}')
        x0, y0, x1, y1 = bounds
        # Small padding preserves the antialiased silhouette and prevents neighboring cells bleeding.
        x0, y0 = max(0, x0 - 3), max(0, y0 - 3)
        x1, y1 = min(right - left, x1 + 3), min(bottom - top, y1 + 3)
        records[name] = {'file': file, 'region': {'x': left + x0, 'y': top + y0, 'width': x1 - x0, 'height': y1 - y0, 'canvasWidth': width, 'canvasHeight': height}}
target = root / 'src/content/sprite-regions.ts'
target.write_text('// Generated by scripts/register-sprites.py; raster originals are untouched.\nexport const spriteRegions = ' + json.dumps(records, ensure_ascii=False, indent=2) + ' as const;\n', encoding='utf-8')
print(f'Registered {len(records)} independent sprite regions.')
