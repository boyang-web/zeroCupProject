"""Register alpha regions only; generated PNG originals remain untouched."""
from pathlib import Path
import json
from PIL import Image

root = Path(__file__).resolve().parent.parent
datasets = [
    ('people-v1.png', 3, 1, ['night-xu', 'night-luo', 'night-liang']),
    ('props-v1.png', 4, 2, ['night-bowl', 'night-box', 'night-phone', 'night-clip', 'night-lamp-on', 'night-lamp-off', 'night-sign', 'night-packed-box']),
    ('extras-v1.png', 2, 1, ['night-empty-bowl', 'night-cloth']),
    ('luo-seated-v1.png', 1, 1, ['night-luo-seated']),
    ('flat-note-v1.png', 1, 1, ['night-flat-note']),
]
records = {}
for filename, cols, rows, ids in datasets:
    im = Image.open(root / 'public/assets/night' / filename)
    if im.mode != 'RGBA':
        raise ValueError(f'{filename} needs generated alpha')
    w, h = im.size
    for i, name in enumerate(ids):
        left, top = round(i % cols * w / cols), round(i // cols * h / rows)
        right, bottom = round((i % cols + 1) * w / cols), round((i // cols + 1) * h / rows)
        box = im.getchannel('A').crop((left, top, right, bottom)).point(lambda a: 255 if a > 160 else 0).getbbox()
        if not box:
            raise ValueError(f'Empty sprite {name}')
        x0, y0, x1, y1 = box
        records[name] = {'file': 'night/' + filename, 'region': {'x': left + max(0,x0-2), 'y': top + max(0,y0-2), 'width': min(right-left,x1+2)-max(0,x0-2), 'height': min(bottom-top,y1+2)-max(0,y0-2), 'canvasWidth': w, 'canvasHeight': h}}
out = '// Generated by scripts/register-night.py; PNG originals unchanged.\nexport const nightRegions = ' + json.dumps(records, ensure_ascii=False, indent=2) + ' as const;\n'
(root / 'src/content/night-regions.ts').write_text(out, encoding='utf-8')
print(f'Registered {len(records)} independent night sprites.')
